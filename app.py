import os
import secrets
import uuid
from pathlib import Path
from werkzeug.utils import secure_filename

from flask import Flask, jsonify, request, send_from_directory, session
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError
from werkzeug.security import check_password_hash, generate_password_hash


BASE_DIR = Path(__file__).resolve().parent
DATABASE = BASE_DIR / "kazoku.db"
ASSETS_DIR = BASE_DIR / "assets"
UPLOADS_DIR = ASSETS_DIR / "uploads"
UPLOADS_DIR.mkdir(parents=True, exist_ok=True)
ALLOWED_IMAGE_EXTENSIONS = {"jpg", "jpeg", "png", "webp"}
DATABASE_URL = os.environ.get("DATABASE_URL")
if DATABASE_URL:
    if DATABASE_URL.startswith("postgres://"):
        DATABASE_URL = DATABASE_URL.replace("postgres://", "postgresql+psycopg://", 1)
    elif DATABASE_URL.startswith("postgresql://"):
        DATABASE_URL = DATABASE_URL.replace("postgresql://", "postgresql+psycopg://", 1)
else:
    DATABASE_URL = f"sqlite:///{DATABASE.as_posix()}"

engine = create_engine(
    DATABASE_URL,
    pool_pre_ping=True,
    connect_args={"check_same_thread": False} if DATABASE_URL.startswith("sqlite:") else {},
)

app = Flask(__name__, static_folder=None)
secret_key = os.environ.get("KAZOKU_SECRET_KEY")
if not secret_key and os.environ.get("RENDER"):
    raise RuntimeError("KAZOKU_SECRET_KEY precisa estar configurada no Render.")
app.secret_key = secret_key or secrets.token_hex(32)

app.config.update(
    SESSION_COOKIE_HTTPONLY=True,
    SESSION_COOKIE_SAMESITE="Lax",
    SESSION_COOKIE_SECURE=os.environ.get("RENDER") is not None,
)


def get_db():
    return engine.begin()


def init_db():
    id_definition = (
        "INTEGER PRIMARY KEY AUTOINCREMENT"
        if engine.dialect.name == "sqlite"
        else "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    )
    with get_db() as connection:
        connection.execute(
            text(f"""
            CREATE TABLE IF NOT EXISTS users (
                id {id_definition},
                name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'student',
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """)
        )
        if engine.dialect.name == "sqlite":
            columns = connection.execute(text("PRAGMA table_info(users)")).mappings().all()
            if "role" not in {column["name"] for column in columns}:
                connection.execute(text("ALTER TABLE users ADD COLUMN role TEXT NOT NULL DEFAULT 'student'"))
        else:
            connection.execute(
                text("""
                ALTER TABLE users
                ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'student'
                """)
            )
        connection.execute(
            text(f"""
            CREATE TABLE IF NOT EXISTS events (
                id {id_definition},
                title TEXT NOT NULL,
                event_date TEXT NOT NULL,
                image_url TEXT NOT NULL,
                created_by INTEGER,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """)
        )


